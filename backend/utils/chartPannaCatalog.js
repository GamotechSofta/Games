/** All chart pannas: SP list + valid double + triple (000…999). */
export function getAllChartPannas() {
    const out = new Set();
    for (const p of VALID_SINGLE_PANAS) out.add(p);
    for (const p of VALID_DOUBLE_PANAS) out.add(p);
    for (let d = 0; d <= 9; d += 1) out.add(`${d}${d}${d}`);
    return [...out].sort((a, b) => Number(a) - Number(b));
}
